# Helper functions for computing graph metrics and topological ordering.
import warnings
import castle
from castle.metrics import MetricsDAG
import numpy as np
import networkx as nx
from sid import *

def compute_graph_metrics(est_dag, true_dag):
# Helper function to compute the confusion matrix and SHD for the estimated DAG compared to the true DAG.
# Inputs: estimated and true DAGs adjacency matrices (numpy arrays). 
# Outputs: a dictionary containing TP, FP, FN, TN, precision, recall, F1 score, and SHD.
    shd = MetricsDAG(est_dag, true_dag).metrics['shd']
    est  = (est_dag  != 0).astype(int)
    true = (true_dag != 0).astype(int)
    np.fill_diagonal(est, 0)
    np.fill_diagonal(true, 0)
    est_flat  = est.flatten()
    true_flat = true.flatten()
    TP = np.sum((est_flat == 1) & (true_flat == 1)).item()
    FP = np.sum((est_flat == 1) & (true_flat == 0)).item()
    FN = np.sum((est_flat == 0) & (true_flat == 1)).item()
    TN = np.sum((est_flat == 0) & (true_flat == 0)).item()
    precision = TP / (TP + FP) if (TP + FP) > 0 else np.nan
    recall = TP / (TP + FN) if (TP + FN) > 0 else np.nan
    F1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else np.nan

    try:
        sid_lower, sid_upper = compute_sid(est_dag, true_dag)
    except ValueError as e:
        warnings.warn(f"SID could not be computed: {e}")
        sid_lower = sid_upper = np.nan

    return {
        'TP': TP,
        'FP': FP,
        'FN': FN,
        'TN': TN,
        'precision': precision,
        'recall': recall,
        'F1': F1,
        'shd': shd,
        'sid_lower': sid_lower,
        'sid_upper': sid_upper,
    }

def get_topological_ordering(adjacency_matrix):
    G = nx.DiGraph(adjacency_matrix)
    try:
        topological_order = list(nx.topological_sort(G))
        return topological_order
    except nx.NetworkXUnfeasible:
        raise ValueError("The graph contains a cycle, so a topological ordering is not possible.")


def compute_analytical_kurtosis(sim):
    """Compute the analytical excess kurtosis of each node's marginal in the pooled distribution.

    The SEM is X = (I - W^T)^{-1} eps, so X_i = sum_j A[i,j] * eps_j where A = (I-W^T)^{-1}.

    In the pooled distribution (interventions generated by independent Bernoulli(p) per node),
    each noise eps_j = delta_per_node[j] * B_j + xi_j, with B_j ~ Bernoulli(p) and xi_j ~ N(0,1),
    all independent. The 4th cumulant is additive and the Gaussian component contributes 0, so:

        a[i,j]    = A[i,j] * delta_per_node[j]          (propagated shift)
        kappa4_i  = p(1-p)(1-6p(1-p)) * sum_j a[i,j]^4  (4th cumulant of X_i)
        var_i     = sum_j A[i,j]^2 + p(1-p) * sum_j a[i,j]^2
        kurtosis_i = kappa4_i / var_i^2                  (excess kurtosis)

    Uses np.linalg.solve to avoid explicit matrix inversion.

    To verify empirically: pool a large-sample simulation (n >= 1e5) across all environments
    and compare scipy.stats.kurtosis(X[:, i], fisher=True) against this function's output.

    Parameters
    ----------
    sim : ShiftSimulation
        Must have delta_per_node set (call _generate_datasets() first) and
        weighted_random_dag available.

    Returns
    -------
    kurtosis : np.ndarray, shape (n_nodes,)
        Excess kurtosis of each node's pooled marginal distribution.
    """
    W = sim.weighted_random_dag
    n = W.shape[0]
    p = sim.p_intervention
    delta_per_node = sim.delta_per_node  # shape (n_nodes,), set by _generate_datasets()

    # Solve (I - W^T) @ A = I  — avoids explicit inversion, uses LU decomposition internally
    A = np.linalg.solve(np.eye(n) - W.T, np.eye(n))  # shape (n, n), A[i,j] = (I-W^T)^{-1}[i,j]

    # Propagated shifts: a[i,j] = A[i,j] * delta_per_node[j]
    a = A * delta_per_node[np.newaxis, :]  # broadcast over rows, shape (n, n)

    # 4th cumulant coefficient for Bernoulli(p)
    bern_kappa4 = p * (1 - p) * (1 - 6 * p * (1 - p))

    kappa4   = bern_kappa4 * np.sum(a ** 4, axis=1)                    # shape (n,)
    var_gauss = np.sum(A ** 2, axis=1)                                  # Gaussian contribution
    var_bern  = p * (1 - p) * np.sum(a ** 2, axis=1)                   # Bernoulli contribution
    var_total = var_gauss + var_bern                                     # shape (n,)

    with np.errstate(invalid='ignore', divide='ignore'):
        kurtosis = np.where(var_total > 0, kappa4 / var_total ** 2, np.nan)
    return kurtosis

